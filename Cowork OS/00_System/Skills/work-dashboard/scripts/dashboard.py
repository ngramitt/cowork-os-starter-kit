#!/usr/bin/env python3
"""
Cowork OS active-work dashboard generator.

Walks every workstation (including nested sub-workstations), extracts the
"Current Status" section from each MEMORY.md, and writes a single
DASHBOARD.md at the workspace root. Deterministic and zero-token: no agent
interpretation involved; the dashboard is only as current as the MEMORY.md
Current Status lines (which the conventions require updating every working
session).

Safety: DASHBOARD.md is the ONLY file this script writes, and it refuses to
overwrite it unless the existing file carries the AUTO-GENERATED marker
(i.e. it will never clobber a hand-made file of the same name).

Usage:
    python3 dashboard.py [WORKSPACE_ROOT] [--stdout] [--full]

--stdout prints instead of writing the file.
--full   restores the pre-2026-09-27 layout (every Current Status in full).

Default layout: one table
row per workstation, grouped Active / Dormant / Closed. The row shows the
status's "Next action" (or its first sentence) and flags a Current Status
over the 80-word budget. Closed and dormant overrides come from
`../lifecycle.txt`; a workstation with no MEMORY.md update in DORMANT_DAYS
is shown as Dormant automatically.
"""

import os
import re
import sys
from datetime import date, datetime
from zoneinfo import ZoneInfo

from pathlib import Path


def _load_local_tz():
    """The owner's timezone from 00_System/workspace-config.txt (written during
    first-run setup). Falls back to this machine's local timezone, so dates
    match the owner's calendar rather than a UTC server clock."""
    here = Path(__file__).resolve()
    for cand in here.parents:
        cfg = cand / "00_System" / "workspace-config.txt"
        if cfg.is_file():
            for line in cfg.read_text(encoding="utf-8").splitlines():
                key, _, val = line.partition("=")
                if key.strip().lower() == "timezone" and val.strip():
                    try:
                        return ZoneInfo(val.strip())
                    except Exception:
                        break
            break
    return datetime.now().astimezone().tzinfo


LOCAL_TZ = _load_local_tz()
from pathlib import Path

MARKER = "<!-- AUTO-GENERATED by 00_System/Skills/work-dashboard — do not hand-edit; re-run dashboard.py instead. -->"
NON_WORKSTATION_DIRS = {"00_Resources", "00_System"}
DORMANT_DAYS = 60          # no MEMORY.md touch for this long = Dormant
STATUS_WORD_BUDGET = 80    # matches workspace-audit's budget
SUMMARY_CHARS = 220
LIFECYCLE_FILE = Path(__file__).parent.parent / "lifecycle.txt"
OVERRIDES_FILE = Path(__file__).parent.parent.parent / "workspace-audit" / "budget-overrides.txt"
IGNORE_DIRS = {".git", "__pycache__", "node_modules"}


def find_root(start: Path):
    for cand in [start.resolve(), *start.resolve().parents]:
        if (cand / "CLAUDE.md").is_file() and (cand / "00_System").is_dir():
            return cand
    return None


def is_workstation(d: Path):
    return (d / "CLAUDE.md").is_file() and (d / "MEMORY.md").is_file()


def extract_section(md_path: Path, heading: str):
    """Return the body of `## <heading>` up to the next ## (stripped)."""
    text = md_path.read_text(encoding="utf-8", errors="replace")
    m = re.search(rf"^##\s+{re.escape(heading)}\s*$(.*?)(?=^##\s|\Z)",
                  text, re.M | re.S)
    if not m:
        return None
    body = m.group(1).strip()
    # drop a leading italic placeholder paragraph, even one that wraps over
    # several lines (_State, blocker, next action... Update every session._)
    if body.startswith("_") and not body.startswith("__"):
        body = re.sub(r"^_[^_]*_[ \t]*\n?", "", body, count=1).strip()
    # drop leading italic placeholder lines like _Update every session._
    lines = [l for l in body.splitlines()
             if not re.match(r"^_[^_]+_\s*$", l.strip())]
    return "\n".join(lines).strip() or None


def collect(root: Path):
    """Yield (label, memory_path, status, mtime) for every workstation."""
    def walk(d: Path, prefix: str):
        for c in sorted(d.iterdir()):
            if (not c.is_dir() or c.name in IGNORE_DIRS
                    or c.name in NON_WORKSTATION_DIRS
                    or c.name.startswith(".")):
                continue
            if is_workstation(c):
                label = f"{prefix}{c.name}"
                mem = c / "MEMORY.md"
                status = extract_section(mem, "Current Status")
                yield (label, mem, status, mem.stat().st_mtime)
                yield from walk(c, f"{label} → ")
    yield from walk(root, "")


def load_lifecycle():
    """{label: (state, note)} from lifecycle.txt; state is closed|dormant."""
    out = {}
    if LIFECYCLE_FILE.is_file():
        for line in LIFECYCLE_FILE.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = [x.strip() for x in line.split("|")]
            if len(parts) >= 2 and parts[1].lower() in {"closed", "dormant"}:
                out[parts[0]] = (parts[1].lower(),
                                 parts[2] if len(parts) > 2 else "")
    return out


def load_status_overrides():
    """{workstation folder path: status word budget} from workspace-audit's
    budget-overrides.txt, so the ⚠ flag matches the audit."""
    out = {}
    if OVERRIDES_FILE.is_file():
        for line in OVERRIDES_FILE.read_text(encoding="utf-8").splitlines():
            parts = [x.strip() for x in line.split("|")]
            if (not line.strip().startswith("#") and len(parts) >= 3
                    and parts[1] == "status_words" and parts[2].isdigit()):
                out[parts[0]] = int(parts[2])
    return out


def open_tasks(ws_dir: Path):
    """Open items under '## Active' in the workstation's Tracking/Tasks.md,
    or None when it has no task list."""
    f = ws_dir / f"{ws_dir.name} Resources" / "Tracking" / "Tasks.md"
    if not f.is_file():
        return None
    m = re.search(r"(?ms)^## Active\s*$(.*?)(?=^## |\Z)", f.read_text(encoding="utf-8", errors="replace"))
    return len(re.findall(r"(?m)^\s*- \[ \]", m.group(1))) if m else 0


def summarize(status):
    """The status's 'Next action' clause if it has one, else its first
    sentence; markdown emphasis stripped, trimmed to SUMMARY_CHARS."""
    if not status:
        return "_No Current Status section._"
    flat = re.sub(r"\*\*|__", "", status)
    flat = re.sub(r"\s+", " ", flat).strip()
    # a sentence ends at . ! ? followed by a capital, markup or the end, so
    # abbreviations such as "vs." or "e.g." don't cut the line short
    END = r"(?:(?<=[.!?])\s(?=[A-Z*_`(\[-])|$)"
    m = re.search(r"(?i:next action[s]?)\s*[:\-]\s*(.+?)" + END, flat)
    if m:
        text = "Next: " + m.group(1).strip()
    else:
        first = re.sub(r"^[-*]\s+", "", flat)
        text = re.split(r"(?<=[.!?])\s(?=[A-Z*_`(\[-])", first, maxsplit=1)[0]
    if len(text) > SUMMARY_CHARS:
        text = text[:SUMMARY_CHARS].rsplit(" ", 1)[0] + "…"
    return text.replace("|", "/")


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    to_stdout = "--stdout" in sys.argv
    full = "--full" in sys.argv
    root = Path(args[0]).resolve() if args else find_root(Path(__file__).parent)
    if not root:
        print("ERROR: couldn't locate workspace root; pass it explicitly.")
        return 2

    today = datetime.now(LOCAL_TZ).date().isoformat()
    out = [MARKER, "",
           f"# Active Work Dashboard — {today}", "",
           "_One place to see where every workstation stands. Generated "
           "from each MEMORY.md \"Current Status\" section; if a status "
           "here is wrong or stale, fix it in that workstation's MEMORY.md "
           "and re-run. Staleness = days since that MEMORY.md was last "
           "modified._", ""]

    rows = list(collect(root))
    if not full:
        life = load_lifecycle()
        overrides = load_status_overrides()
        groups = {"Active": [], "Dormant": [], "Closed": []}
        for label, mem, status, mtime in rows:
            age = (datetime.now() - datetime.fromtimestamp(mtime)).days
            state, note = life.get(label, ("", ""))
            if state == "closed":
                key = "Closed"
            elif state == "dormant" or age > DORMANT_DAYS:
                key = "Dormant"
            else:
                key = "Active"
            sw = len(status.split()) if status else 0
            budget = overrides.get(str(mem.parent.relative_to(root)), STATUS_WORD_BUDGET)
            flag = f" ⚠ status {sw} words" if sw > budget else ""
            n_open = open_tasks(mem.parent)
            tasks_cell = "—" if n_open is None else str(n_open)
            groups[key].append((label, age, summarize(status), flag, note, tasks_cell))
        out[4] = ("_One line per workstation, generated from each MEMORY.md "
                  "\"Current Status\". Fix a wrong row in that MEMORY.md and "
                  "re-run; never hand-edit this file. ⚠ marks a Current "
                  f"Status over the {STATUS_WORD_BUDGET}-word budget. "
                  f"Dormant = no MEMORY.md update in {DORMANT_DAYS}+ days or "
                  "marked in 00_System/Skills/work-dashboard/lifecycle.txt; "
                  "Closed = marked closed there. Open tasks = unchecked items "
                  "under Active in that workstation's Tracking/Tasks.md (— = no "
                  "task list). `--full` shows every status in full._")
        for key in ("Active", "Dormant", "Closed"):
            items = sorted(groups[key], key=lambda r: r[1])
            out.append(f"## {key} ({len(items)})")
            out.append("")
            if not items:
                out.append("_None._")
                out.append("")
                continue
            out.append("| Workstation | Updated | Open tasks | Where it stands |")
            out.append("| --- | --- | --- | --- |")
            for label, age, summ, flag, note, tasks_cell in items:
                extra = f" _({note})_" if note and key != "Active" else ""
                out.append(f"| {label} | {age}d ago{flag} | {tasks_cell} | {summ}{extra} |")
            out.append("")
        content = "\n".join(out) + "\n"
        return write_out(root, content, to_stdout, len(rows))

    stale_cut = 21  # days without a MEMORY.md touch = probably dormant
    active, quiet = [], []
    for label, mem, status, mtime in rows:
        age = (datetime.now() - datetime.fromtimestamp(mtime)).days
        (active if age <= stale_cut else quiet).append(
            (label, status, age))

    def emit(section, items):
        out.append(f"## {section}")
        out.append("")
        if not items:
            out.append("_None._")
            out.append("")
            return
        for label, status, age in items:
            out.append(f"### {label}  ·  updated {age}d ago")
            out.append("")
            out.append(status if status else
                       "_No Current Status section found in MEMORY.md._")
            out.append("")

    emit(f"Recently active (MEMORY.md touched within {stale_cut} days)",
         active)
    emit("Quiet (no MEMORY.md update in 21+ days — dormant or needs a "
         "status refresh)", quiet)

    content = "\n".join(out) + "\n"
    return write_out(root, content, to_stdout, len(rows))


def write_out(root, content, to_stdout, n):
    if to_stdout:
        print(content)
        return 0
    dest = root / "DASHBOARD.md"
    if dest.exists() and MARKER not in dest.read_text(
            encoding="utf-8", errors="replace"):
        print(f"REFUSING to overwrite {dest} — it exists but lacks the "
              f"AUTO-GENERATED marker, so it may be hand-made. Rename or "
              f"remove it first (with the owner's confirmation).")
        return 1
    dest.write_text(content, encoding="utf-8")
    print(f"Wrote {dest} ({n} workstations).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
